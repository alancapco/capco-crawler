#!/usr/bin/env bash
# Run the capco_articles knowledge graph: Neo4j in Docker, llm-graph-builder backend and frontend from source.
#
#   ./graph.sh setup     clone llm-graph-builder, install backend and frontend dependencies
#   ./graph.sh start     start Neo4j, backend (:8000), and frontend (:8080)
#   ./graph.sh stop      stop all three
#   ./graph.sh restart
#   ./graph.sh status
#   ./graph.sh logs [backend|frontend|neo4j]
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
UPSTREAM_REPO="https://github.com/neo4j-labs/llm-graph-builder.git"
UPSTREAM_REF="a728de68d8c75720081816d47b5900a84d93fdcf"
VENDOR="$ROOT/vendor/llm-graph-builder"
BACKEND="$VENDOR/backend"
FRONTEND="$VENDOR/frontend"
RUN_DIR="$ROOT/.run"
LOG_DIR="$RUN_DIR/logs"
BACKEND_PORT=8000
FRONTEND_PORT=8080

log() { printf '%s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

# Read KEY=VALUE lines from .env without executing them. Values already in the environment win.
load_env() {
  local file="$ROOT/.env" line key val
  [ -f "$file" ] || die ".env not found. Copy .env.example to .env and fill in the LLM settings."
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in ''|'#'*) continue ;; *=*) ;; *) continue ;; esac
    key="${line%%=*}"
    key="${key//[[:space:]]/}"
    val="${line#*=}"
    case "$val" in \"*\") val="${val:1:${#val}-2}" ;; \'*\') val="${val:1:${#val}-2}" ;; esac
    [[ "$key" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue
    if [ -z "${!key+x}" ]; then export "$key=$val"; fi
  done < "$file"

  : "${NEO4J_USERNAME:=neo4j}" "${NEO4J_PASSWORD:=capco-graph-change-me}" "${NEO4J_DATABASE:=neo4j}"
  : "${EMBEDDING_MODEL:=BAAI/bge-m3}" "${EMBEDDING_DIMENSION:=1024}"
  : "${LLM_MAX_CONCURRENCY:=2}" "${LLM_MAX_RETRIES:=8}"
  [ -n "${EMBEDDING_MODEL_DIR:-}" ] || die "set EMBEDDING_MODEL_DIR in .env to a local sentence-transformers model directory"
}

dotenv_line() {
  local val="${2//\\/\\\\}"
  printf '%s="%s"\n' "$1" "${val//\"/\\\"}"
}

# Resolve a Hugging Face cache repo (models--org--name) or plain folder to a complete model directory.
embedding_snapshot() {
  local dir
  for dir in "$EMBEDDING_MODEL_DIR"/snapshots/*/ "$EMBEDDING_MODEL_DIR"/; do
    if [ -f "${dir}modules.json" ] && [ -f "${dir}config.json" ] \
      && { [ -f "${dir}pytorch_model.bin" ] || [ -f "${dir}model.safetensors" ]; }; then
      printf '%s\n' "${dir%/}"
      return
    fi
  done
  die "no sentence-transformers model found in EMBEDDING_MODEL_DIR=$EMBEDDING_MODEL_DIR"
}

write_backend_env() {
  [ -n "${LLM_MODEL:-}" ] && [ -n "${LLM_BASE_URL:-}" ] && [ -n "${LLM_API_KEY:-}" ] \
    || die "set LLM_MODEL, LLM_BASE_URL, and LLM_API_KEY in .env"
  case "$LLM_MODEL$LLM_BASE_URL$LLM_API_KEY" in
    *,*) die "LLM_MODEL, LLM_BASE_URL, and LLM_API_KEY cannot contain commas (llm-graph-builder stores them as model,base_url,api_key)" ;;
  esac

  # The upstream loader always reads ./local_model relative to the backend directory.
  ln -sfn "$(embedding_snapshot)" "$BACKEND/local_model"

  # The dropdown id must not contain OPENAI: upstream sends any OPENAI model to api.openai.com.
  {
    echo "# Generated by graph.sh from ../../../.env. Edits here are overwritten on start."
    dotenv_line LLM_MODEL_CONFIG_CAPCO_COMPATIBLE "$LLM_MODEL,$LLM_BASE_URL,$LLM_API_KEY"
    dotenv_line GRAPH_CLEANUP_MODEL capco_compatible
    dotenv_line NEO4J_URI "bolt://localhost:7687"
    dotenv_line NEO4J_USERNAME "$NEO4J_USERNAME"
    dotenv_line NEO4J_PASSWORD "$NEO4J_PASSWORD"
    dotenv_line NEO4J_DATABASE "$NEO4J_DATABASE"
    dotenv_line EMBEDDING_PROVIDER sentence-transformer
    dotenv_line EMBEDDING_MODEL "$EMBEDDING_MODEL"
    dotenv_line EMBEDDING_DIMENSION "$EMBEDDING_DIMENSION"
    dotenv_line LLM_MAX_CONCURRENCY "$LLM_MAX_CONCURRENCY"
    dotenv_line LLM_MAX_RETRIES "$LLM_MAX_RETRIES"
    dotenv_line IS_EMBEDDING true
    dotenv_line ENTITY_EMBEDDING false
    dotenv_line GCS_FILE_CACHE false
    dotenv_line TRACK_USER_USAGE false
    dotenv_line AUTHENTICATION_REQUIRED false
    dotenv_line ENABLE_USER_AGENT true
    dotenv_line USER_AGENT capco-crawler
    dotenv_line KNN_MIN_SCORE "${KNN_MIN_SCORE:-0.9}"
    dotenv_line MAX_TOKEN_CHUNK_SIZE "${MAX_TOKEN_CHUNK_SIZE:-10000}"
    dotenv_line UPDATE_GRAPH_CHUNKS_PROCESSED "${UPDATE_GRAPH_CHUNKS_PROCESSED:-20}"
    dotenv_line ALLOWED_FRONTEND_ORIGINS "*"
    dotenv_line HF_HUB_OFFLINE 1
    dotenv_line TRANSFORMERS_OFFLINE 1
    dotenv_line NLTK_DATA "$BACKEND/nltk_data"
  } > "$BACKEND/.env"
  chmod 600 "$BACKEND/.env"
}

write_frontend_env() {
  {
    echo "# Generated by graph.sh. Edits here are overwritten on start."
    dotenv_line VITE_BACKEND_API_URL "http://localhost:$BACKEND_PORT"
    dotenv_line VITE_REACT_APP_SOURCES local
    dotenv_line VITE_ENV DEV
    dotenv_line VITE_LLM_MODELS capco_compatible
    dotenv_line VITE_LLM_MODELS_PROD capco_compatible
    dotenv_line VITE_SKIP_AUTH true
    dotenv_line VITE_CHAT_MODES "vector,graph,graph_vector,fulltext,graph_vector_fulltext,entity_vector,global_vector"
    dotenv_line VITE_BLOOM_URL "https://workspace-preview.neo4j.io/workspace/explore?connectURL={CONNECT_URL}&search=Show+me+a+graph&featureGenAISuggestions=true&featureGenAISuggestionsInternal=true"
    dotenv_line VITE_TIME_PER_PAGE 50
    dotenv_line VITE_CHUNK_SIZE 1048576
    dotenv_line VITE_LARGE_FILE_SIZE 5242880
    dotenv_line VITE_TOKENS_PER_CHUNK 500
    dotenv_line VITE_CHUNK_OVERLAP 20
    dotenv_line VITE_CHUNK_TO_COMBINE 1
    dotenv_line VITE_BATCH_SIZE 2
    dotenv_line VITE_FRONTEND_HOSTNAME "localhost:$FRONTEND_PORT"
  } > "$FRONTEND/.env"
}

cmd_setup() {
  command -v uv >/dev/null || die "uv is required (https://docs.astral.sh/uv/)"
  command -v node >/dev/null || die "Node.js is required"

  if [ ! -d "$VENDOR/.git" ]; then
    log "Cloning llm-graph-builder into vendor/"
    git clone --filter=blob:none --no-checkout "$UPSTREAM_REPO" "$VENDOR"
  fi
  git -C "$VENDOR" sparse-checkout set backend frontend
  if [ "$(git -C "$VENDOR" rev-parse HEAD 2>/dev/null)" != "$UPSTREAM_REF" ]; then
    git -C "$VENDOR" fetch --depth 1 origin "$UPSTREAM_REF"
    git -C "$VENDOR" checkout --quiet "$UPSTREAM_REF"
  fi

  log "Patching backend"
  python3 "$ROOT/scripts/patch_backend.py" "$BACKEND"

  log "Installing backend dependencies (Python 3.12)"
  [ -x "$BACKEND/.venv/bin/python" ] || uv venv --python 3.12 "$BACKEND/.venv"
  # Upstream pins Linux CPU wheels (torch==x+cpu from the PyTorch index); macOS uses the PyPI builds.
  sed -E -e '/^--extra-index-url/d' -e 's/^(torch[a-z]*==[0-9.]+)\+cpu$/\1/' \
    "$BACKEND/requirements.txt" > "$BACKEND/requirements.host.txt"
  VIRTUAL_ENV="$BACKEND/.venv" uv pip install -r "$BACKEND/requirements.host.txt"
  "$BACKEND/.venv/bin/python" -m nltk.downloader -q -d "$BACKEND/nltk_data" punkt punkt_tab averaged_perceptron_tagger averaged_perceptron_tagger_eng

  log "Installing frontend dependencies"
  (cd "$FRONTEND" && HUSKY=0 npx --yes yarn@1.22.22 install --frozen-lockfile)

  log "Setup complete. Run ./graph.sh start"
}

pid_of() {
  local file="$RUN_DIR/$1.pid" pid
  [ -f "$file" ] || return 1
  pid="$(cat "$file")"
  if kill -0 "$pid" 2>/dev/null; then printf '%s\n' "$pid"; else rm -f "$file"; return 1; fi
}

port_busy() { lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1; }

wait_for_url() {
  local url="$1" name="$2" pid="$3" tries="$4"
  for ((i = 0; i < tries; i++)); do
    curl -fsS -o /dev/null "$url" 2>/dev/null && return 0
    kill -0 "$pid" 2>/dev/null || die "$name exited during startup. See .run/logs/$name.log"
    sleep 2
  done
  die "$name did not answer at $url. See .run/logs/$name.log"
}

start_neo4j() {
  log "Starting Neo4j"
  (cd "$ROOT" && docker compose up -d --wait --remove-orphans neo4j >/dev/null)
}

# Start a command in its own session so it keeps running after this script exits.
detach() {
  local name="$1" dir="$2"
  shift 2
  : > "$LOG_DIR/$name.log"
  python3 -c '
import os, sys
directory, logfile, pidfile = sys.argv[1:4]
cmd = sys.argv[4:]
pid = os.fork()
if pid:
    open(pidfile, "w").write(str(pid))
    raise SystemExit(0)
os.setsid()
os.chdir(directory)
fd = os.open(logfile, os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o644)
os.dup2(fd, 1)
os.dup2(fd, 2)
os.execvp(cmd[0], cmd)
' "$dir" "$LOG_DIR/$name.log" "$RUN_DIR/$name.pid" "$@"
}

start_backend() {
  if pid_of backend >/dev/null; then log "Backend already running"; return; fi
  port_busy "$BACKEND_PORT" && die "port $BACKEND_PORT is already in use"
  [ -x "$BACKEND/.venv/bin/uvicorn" ] || die "backend is not installed. Run ./graph.sh setup"
  write_backend_env
  log "Starting backend on http://localhost:$BACKEND_PORT (first start loads the embedding model)"
  # Bind all IPv4 interfaces so both localhost and 127.0.0.1 work in the browser.
  detach backend "$BACKEND" "$BACKEND/.venv/bin/uvicorn" score:app --host 0.0.0.0 --port "$BACKEND_PORT"
  wait_for_url "http://127.0.0.1:$BACKEND_PORT/health" backend "$(cat "$RUN_DIR/backend.pid")" 90
}

start_frontend() {
  if pid_of frontend >/dev/null; then log "Frontend already running"; return; fi
  port_busy "$FRONTEND_PORT" && die "port $FRONTEND_PORT is already in use"
  [ -x "$FRONTEND/node_modules/.bin/vite" ] || die "frontend is not installed. Run ./graph.sh setup"
  write_frontend_env
  log "Starting frontend on http://localhost:$FRONTEND_PORT"
  detach frontend "$FRONTEND" "$FRONTEND/node_modules/.bin/vite" --host 0.0.0.0 --port "$FRONTEND_PORT" --strictPort
  wait_for_url "http://127.0.0.1:$FRONTEND_PORT" frontend "$(cat "$RUN_DIR/frontend.pid")" 30
}

stop_process() {
  local name="$1" pid
  pid="$(pid_of "$name")" || { log "$name not running"; return; }
  log "Stopping $name (pid $pid)"
  kill -TERM -- "-$pid" 2>/dev/null || kill "$pid" 2>/dev/null || true
  for _ in $(seq 1 20); do kill -0 "$pid" 2>/dev/null || break; sleep 0.5; done
  kill -KILL -- "-$pid" 2>/dev/null || kill -9 "$pid" 2>/dev/null || true
  rm -f "$RUN_DIR/$name.pid"
}

cmd_start() {
  load_env
  mkdir -p "$LOG_DIR"
  start_neo4j
  start_backend
  start_frontend
  log ""
  log "Graph UI:      http://localhost:$FRONTEND_PORT"
  log "Backend API:   http://localhost:$BACKEND_PORT/docs"
  log "Neo4j Browser: http://localhost:7474"
  log "Logs:          ./graph.sh logs [backend|frontend|neo4j]"
}

cmd_stop() {
  stop_process frontend
  stop_process backend
  log "Stopping Neo4j"
  (cd "$ROOT" && docker compose stop neo4j >/dev/null)
}

cmd_status() {
  local pid state
  for name in backend frontend; do
    if pid="$(pid_of "$name")"; then log "$name: running (pid $pid)"; else log "$name: stopped"; fi
  done
  state="$(docker inspect -f '{{.State.Status}}{{if .State.Health}} ({{.State.Health.Status}}){{end}}' capco-graph-neo4j 2>/dev/null || echo 'not created')"
  log "neo4j: $state"
  if curl -fsS -o /dev/null "http://localhost:$BACKEND_PORT/health" 2>/dev/null; then
    log "backend health: ok"
  fi
}

cmd_logs() {
  case "${1:-backend}" in
    backend|frontend) tail -n 100 -f "$LOG_DIR/$1.log" ;;
    neo4j) (cd "$ROOT" && docker compose logs -f --tail 100 neo4j) ;;
    *) die "usage: ./graph.sh logs [backend|frontend|neo4j]" ;;
  esac
}

case "${1:-}" in
  setup) cmd_setup ;;
  start) cmd_start ;;
  stop) cmd_stop ;;
  restart) cmd_stop; cmd_start ;;
  status) cmd_status ;;
  logs) cmd_logs "${2:-backend}" ;;
  *) sed -n '2,9p' "$0" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
